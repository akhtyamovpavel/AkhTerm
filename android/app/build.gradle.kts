val akhtermVersionName = providers.gradleProperty("akhtermVersionName").orElse("1.5.1").get()
val akhtermVersionCode = providers.gradleProperty("akhtermVersionCode")
    .map { it.toInt() }
    .orElse(computeVersionCode(akhtermVersionName))
    .get()

fun computeVersionCode(version: String): Int {
    val clean = version.removePrefix("v").substringBefore("-")
    val parts = clean.split(".").mapNotNull { it.toIntOrNull() }
    val major = parts.getOrElse(0) { 1 }
    val minor = parts.getOrElse(1) { 0 }
    val patch = parts.getOrElse(2) { 0 }
    return major * 10000 + minor * 100 + patch
}

